def model_card(title, features, diff, shots, auc_key=None, ui=None, extra=None, auc_src="офіційні набори toksym"):
    s = new_slide(title, notes="Картка моделі: скриншот заліку і відмінність від інших моделей.")
    y = 1.4
    for name, cap, w in shots:
        ww, hh = pic(s, name, 0.6, y, w=w, border=True)
        if name.endswith("_auc.png"):
            cap += f" (поле «поріг» замінено на ROC AUC; {auc_src})"
        fig_cap(s, 0.6, y + hh + 0.06, w, cap)
        y += hh + 0.62
    if any(n.endswith("_auc.png") for n, _, _ in shots):
        thr_box(s, 0.6, y - 0.02, w, THR_NOTE)
    points(s, 8.0, 1.45, 4.75, [("Ознаки", features)] + [("Відмінність", d) for d in diff[:1]] +
           [("", d) for d in diff[1:]], size=13, gap=8)
    rows = [["показник", "значення"]] + (ui or [])
    if auc_key:
        a = AUC[auc_key]
        rows += [["ROC AUC, 30 мс", f3(a["0.03"])], ["ROC AUC, 0,1 с", f3(a["0.1"])], ["об'єм", f3(a["volume"])]]
    rows += extra or []
    tab_cap(s, 8.0, 4.05, 4.75, "Показники" + (" (офіційні набори toksym)" if auc_key else ""))
    table(s, 8.0, 4.45, 4.75, rows, [2.75, 2.0], row_h=0.38, sizes=[[11, 11]] + [[11, 12]] * (len(rows) - 1))


